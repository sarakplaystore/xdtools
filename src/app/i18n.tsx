interface I18nValue {
  lang: Lang;
  setLang(l: Lang): void;
  t(key: Key): string;
}

const I18nContext = createContext<I18nValue>({ lang: 'en', setLang: () => {}, t: (k) => en[k] });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem('xd-lang');
      if (saved === 'en' || saved === 'km') return saved;
    } catch {
      /* storage unavailable */
    }
    return navigator.language?.toLowerCase().startsWith('km') ? 'km' : 'en';
  });
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem('xd-lang', l);
    } catch {
      /* ignore */
    }
  }, []);
  const t = useCallback((key: Key) => (lang === 'km' ? (km[key] ?? en[key]) : en[key]), [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
